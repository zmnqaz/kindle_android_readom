"""Stage vendor/amazon/pw4-hardware: the PW4 kernel build's modules that
Android loads from /vendor/lib/modules (device/amazon/pw4/hardware/*.rc), and
pw4-hardware.mk, which device/amazon/pw4/pw4.mk includes.

The modules are built from the GPL kernel tree with this repository's
patches; they are copied, debug info stripped, and never committed.
"""
import argparse, shutil, subprocess, sys
from pathlib import Path

MODULES = {
    'configfs.ko': 'fs/configfs/configfs.ko',
    'libcomposite.ko': 'drivers/usb/gadget/libcomposite.ko',
    'usb_f_fs.ko': 'drivers/usb/gadget/function/usb_f_fs.ko',
    'usb_f_mtp.ko': 'drivers/usb/gadget/function/usb_f_mtp.ko',
    'bcmdhd.ko': 'drivers/net/wireless/bcmdhd/bcmdhd.ko',
}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--kernel-build', type=Path, required=True, help='the O= directory of the PW4 Android kernel')
    ap.add_argument('--strip', required=True, help='the ARM strip of the kernel toolchain')
    ap.add_argument('--aosp', type=Path, required=True)
    a = ap.parse_args()
    release = (a.kernel_build / 'include/config/kernel.release').read_text().strip()
    out = a.aosp / 'vendor/amazon/pw4-hardware'
    if out.exists():
        shutil.rmtree(out)
    mods = out / 'vendor/lib/modules'
    mods.mkdir(parents=True)
    for name, rel in MODULES.items():
        src = a.kernel_build / rel
        data = src.read_bytes()
        if b'vermagic=%s ' % release.encode() not in data:
            sys.exit('%s is not of kernel %s' % (src, release))
        subprocess.run([a.strip, '--strip-debug', '-o', str(mods / name), str(src)], check=True)
    lines = ['# Generated by device/amazon/pw4/porting/stage-pw4-hardware.py for kernel ' + release,
             'PRODUCT_COPY_FILES += \\']
    lines += ['    vendor/amazon/pw4-hardware/vendor/lib/modules/%s:$(TARGET_COPY_OUT_VENDOR)/lib/modules/%s \\' % (n, n)
              for n in MODULES]
    lines[-1] = lines[-1][:-2]
    (out / 'pw4-hardware.mk').write_text('\n'.join(lines) + '\n')
    for p in sorted(mods.iterdir()):
        print('%8d %s' % (p.stat().st_size, p.name))


if __name__ == '__main__':
    main()
